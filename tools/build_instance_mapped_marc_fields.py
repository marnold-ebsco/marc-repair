"""Regenerate instance_mapped_marc_fields.txt from FOLIO's default MARC bib mapping rules.

Usage: .venv/bin/python tools/build_instance_mapped_marc_fields.py [marc_bib_rules.json]

With no argument the rules are downloaded from folio-org/mod-source-record-manager
(the default "MARC bib to instance" rules, `marc_bib_rules.json`). Pass a local
file to use a rules export from your own tenant instead. Only the tags that have
a rule are used (tag level; subfields, indicators and conditions are ignored).
A tag with no rule is "unmapped": it stays on the MARC record but does not show
up in the instance record. The file's hand-edited [ignored] section (tags the
check never lists) is kept when regenerating.
"""
import json
import sys
import urllib.request
from datetime import date
from pathlib import Path

URL = (
    "https://raw.githubusercontent.com/folio-org/mod-source-record-manager/master/"
    "mod-source-record-manager-server/src/main/resources/rules/marc_bib_rules.json"
)
OUT = Path(__file__).resolve().parent.parent / "instance_mapped_marc_fields.txt"


def targets(rules: list) -> list[str]:
    """The instance properties a tag's rules write to (for the comment column)."""
    found: list[str] = []
    for rule in rules:
        for ent in rule.get("entity", [rule]):
            target = ent.get("target")
            if target and target not in found:
                found.append(target)
    return found


DEFAULT_IGNORED = [
    "# Tags never listed by the unmapped_marc_fields check, one TAG or FIRST-LAST range per",
    "# line (optionally followed by | comment). Edit freely: regenerating keeps this section.",
    "010-199 | control numbers, coded data, call numbers and classification (01x-19x)",
    "300-399 | RDA attributes (3xx)",
    "700-789 | added entries and linking entries (the 79x local range stays listed)",
    "800-889 | series added entries and holdings/alternate graphics (89x local range stays listed)",
]


def kept_ignored() -> list[str]:
    """The existing file's [ignored] section lines (so hand edits survive a
    regeneration), or the defaults if there is none."""
    if not OUT.exists():
        return DEFAULT_IGNORED
    kept: list[str] = []
    in_section = False
    for line in OUT.read_text(encoding="utf-8").splitlines():
        if line.strip() == "[ignored]":
            in_section = True
        elif line.strip().startswith("[") and in_section:
            break
        elif in_section:
            kept.append(line)
    while kept and not kept[-1].strip():
        kept.pop()
    return kept or DEFAULT_IGNORED


def main() -> None:
    if len(sys.argv) > 1:
        source = sys.argv[1]
        data = json.loads(Path(source).read_text(encoding="utf-8"))
    else:
        source = URL
        with urllib.request.urlopen(URL, timeout=60) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    tags = sorted(t for t in data if len(t) == 3 and t.isdigit())
    lines = [
        "# MARC bib tags that FOLIO's default MARC-bib-to-instance mapping rules map to the",
        "# instance record. Any other tag is not mapped: it stays on the MARC record but does",
        "# not show up in the instance record (see the unmapped_marc_fields check).",
        "# Tag level only: a tag with a rule counts as mapped even if the rule depends on",
        "# indicators or subfields.",
        "# Generated by tools/build_instance_mapped_marc_fields.py -- do not edit [mapped] by",
        "# hand; regenerate it (or pass your tenant's rules export) instead. [ignored] is yours",
        "# to edit and survives regeneration.",
        f"# Source: {source}",
        f"# Generated: {date.today().isoformat()}",
        "",
        "[mapped]",
    ]
    for tag in tags:
        lines.append(f"{tag} | {', '.join(targets(data[tag])) or '(see rules)'}")
    lines += ["", "[ignored]"] + kept_ignored()
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(tags)} tag(s) to {OUT}")


if __name__ == "__main__":
    main()
