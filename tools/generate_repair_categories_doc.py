def _render_table(rows: list[CategoryRow]) -> str:
    lines = [
        "| " + " | ".join(TABLE_COLUMNS) + " |",
        "|" + "---|" * len(TABLE_COLUMNS),
    ]
    lines.extend(row.as_table_row() for row in rows)
    return "\n".join(lines)


def render_doc() -> str:
    parts = [
        HEADER,
        "## Bib pipeline (`main()`, no split/holdings flags)\n",
        _render_table(BIB_ROWS),
        "\n## Holdings pipeline (`repair_holdings_records`, via "
        "`--split-bib-holdings` or `--repair-holdings`)\n",
        _render_table(HOLDINGS_ROWS),
        FOOTER,
    ]
    return "\n".join(parts).rstrip("\n") + "\n"


def main() -> None:
    with open(DOCS_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_doc())
    print(f"wrote {DOCS_PATH}")


if __name__ == "__main__":
    main()
